export function PricingFaq() {
  const { i18n } = useTranslation("pricing");
  const isBn = i18n.language === "bn";
  const [openIdx, setOpenIdx] = useState<number | null>(null);

  const toggle = (idx: number) => {
    setOpenIdx((prev) => (prev === idx ? null : idx));
  };

  return (
    <motion.section
      initial={{ opacity: 0, y: 20 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true }}
      transition={{ duration: 0.5 }}
      className="mt-24 max-w-4xl mx-auto mb-16"
    >
      <div className="text-center mb-10">
        <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-primary/10 text-primary text-xs font-semibold mb-3 border border-primary/20">
          <HelpCircle className="w-3.5 h-3.5" />
          {isBn ? "সাধারণ জিজ্ঞাসা" : "Frequently Asked Questions"}
        </div>
        <h2 className="text-3xl font-bold tracking-tight">
          {isBn ? "প্রাইসিং সম্পর্কিত সাধারণ প্রশ্নোত্তর" : "Pricing & Billing FAQs"}
        </h2>
        <p className="mt-2 text-sm text-muted-foreground">
          {isBn
            ? "প্ল্যান, পেমেন্ট এবং বিলিং সম্পর্কিত প্রয়োজনীয় তথ্যাবলি।"
            : "Everything you need to know about plans, billing, and payments."}
        </p>
      </div>

      <div className="space-y-3.5">
        {FAQS.map((faq, idx) => {
          const isOpen = openIdx === idx;
          return (
            <div
              key={idx}
              className="rounded-2xl border border-border bg-card/60 backdrop-blur-md overflow-hidden transition-all duration-200 hover:border-primary/40"
            >
              <button
                type="button"
                onClick={() => toggle(idx)}
                className="w-full flex items-center justify-between p-5 text-left font-semibold text-sm sm:text-base text-foreground"
                aria-expanded={isOpen}
              >
                <span>{isBn ? faq.qBn : faq.qEn}</span>
                <ChevronDown
                  className={`w-4 h-4 text-primary shrink-0 transition-transform duration-200 ${
                    isOpen ? "rotate-180" : ""
                  }`}
                />
              </button>

              <AnimatePresence initial={false}>
                {isOpen && (
                  <motion.div
                    key="content"
                    initial={{ height: 0, opacity: 0 }}
                    animate={{ height: "auto", opacity: 1 }}
                    exit={{ height: 0, opacity: 0 }}
                    transition={{ duration: 0.25, ease: "easeInOut" }}
                  >
                    <div className="px-5 pb-5 text-sm text-muted-foreground leading-relaxed border-t border-border/40 pt-3">
                      {isBn ? faq.aBn : faq.aEn}
                    </div>
                  </motion.div>
                )}
              </AnimatePresence>
            </div>
          );
        })}
      </div>
    </motion.section>
  );
}
